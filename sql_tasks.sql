 Необходимо пояснить: что делает запрос, что в приведенном коде является 
 неоптимальным (метаданные менять нельзя). Предложите свой вариант запроса, который 
 решает ту же самую задачу более оптимальным способом.
 
      create table T( [id] int identity(1,1) 

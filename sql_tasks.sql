У нас есть две таблицы, которые связанны через тригер. При вставке в таблицу T тригер автоматически вставляет ту же пару (id, fio) в T2.

      declare @id int 
              , @fio varchar(16)
  
      set @fio = 'ivanov i.i.'
  
      insert into T( [fio] ) values ( @fio ) 
      select @id = [id] from T where [fio] = @fio

Мы вставляем ФИО в таблицу T и пытаемся найти ID по ФИО, что не гарантирует получение искомого ID. ФИО не уникален, мы получим все id с одинаковым ФИО. + лишнее обращение к таблице
Для более оптимального решения мы можем использовать SCOPE_IDENTITY() функцию, которая возвращает последнее значение id, созданное в текущем соединении
    DECLARE @id int
        , @fio varchar(16);

    SET @fio = 'ivanov i.i.';
    
    INSERT INTO T (fio)
    VALUES (@fio);
    
    SET @id = CAST(SCOPE_IDENTITY() AS int);

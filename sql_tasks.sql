      WITH bounds AS (
          SELECT
              date_trunc('month', $1::date)::date AS month_start,
              (
                  date_trunc('month', $1::date)
                  + INTERVAL '1 month'
              )::date AS month_end
      ),
      workdays AS (
          SELECT
              b.month_start + g.day_offset AS work_date
          FROM bounds AS b
          CROSS JOIN LATERAL generate_series(
              0,
              b.month_end - b.month_start - 1
          ) AS g(day_offset)
          WHERE EXTRACT(
              ISODOW FROM b.month_start + g.day_offset
          ) BETWEEN 1 AND 5
      ),
      daily_arrivals AS (
          SELECT
              s.username,
              s.eventdatetime::date AS work_date,
              MIN(s.eventdatetime) AS arrival_time
          FROM stat AS s
          WHERE s.eventdatetime >= (SELECT month_start FROM bounds)
            AND s.eventdatetime <  (SELECT month_end FROM bounds)
          GROUP BY
              s.username,
              s.eventdatetime::date
      ),
      employees AS (
          SELECT u.username
          FROM users AS u
      
          UNION
      
          SELECT d.username
          FROM daily_arrivals AS d
      )
      SELECT
          e.username,
          (SELECT COUNT(*) FROM workdays)
          - COUNT(*) FILTER (
              WHERE EXTRACT(ISODOW FROM d.work_date) BETWEEN 1 AND 5
                AND d.arrival_time <= d.work_date + TIME '09:40:00'
          ) AS late_count
      FROM employees AS e
      LEFT JOIN daily_arrivals AS d
          ON d.username = e.username
      GROUP BY
          e.username
      ORDER BY
